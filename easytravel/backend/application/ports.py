"""Small persistence ports. Application owns each unit-of-work scope."""
from collections.abc import Callable
from contextlib import AbstractAsyncContextManager
from typing import Protocol

from ..domain.models import ChangeProposal, ConfirmedSnapshot, SpecificAuthorization, Trip, WorkingDraft


class PlanRepository(Protocol):
    async def create(self, draft: WorkingDraft) -> Trip: ...
    async def trip(self, trip_id: str) -> Trip: ...
    async def working(self, trip_id: str) -> WorkingDraft: ...
    async def snapshot(self, snapshot_id: str) -> ConfirmedSnapshot: ...
    async def proposal(self, proposal_id: str) -> ChangeProposal: ...
    async def save_proposal(self, proposal: ChangeProposal) -> None: ...
    async def authorization(self, authorization_id: str) -> tuple[SpecificAuthorization, str | None]: ...
    async def save_authorization(self, grant: SpecificAuthorization) -> None: ...
    async def consume(self, authorization_id: str, operation_id: str) -> None: ...
    async def lock_operation(self, operation_id: str) -> None: ...
    async def receipt(self, operation_id: str, request_hash: str) -> dict | None: ...
    async def save_receipt(self, operation_id: str, trip_id: str, kind: str,
                           request_hash: str, result: dict) -> None: ...
    async def advance(self, current: WorkingDraft, updated: WorkingDraft) -> None: ...
    async def save_snapshot(self, snapshot: ConfirmedSnapshot) -> ConfirmedSnapshot: ...
    async def point_snapshot(self, draft: WorkingDraft, snapshot_id: str) -> None: ...


UnitOfWorkFactory = Callable[[str], AbstractAsyncContextManager[PlanRepository]]
